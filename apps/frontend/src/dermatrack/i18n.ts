export type Translator = (key: string, vars?: Record<string, string | number>) => string;

export function useT(lang: Lang): Translator {
  return useMemo(() => {
    const dict = STR[lang] || STR.de;
    return (key, vars) => {
      let s = dict[key] || STR.de[key] || key;
      if (vars) Object.keys(vars).forEach((k) => { s = s.replace(`{${k}}`, String(vars[k])); });
      return s;
    };
  }, [lang]);
}

export const fmtDate = (d: Date, lang: Lang = "de") =>
  new Intl.DateTimeFormat(lang === "de" ? "de-DE" : "en-GB", { day: "2-digit", month: "short" }).format(d);

export const fmtDay = (d: Date, lang: Lang = "de") =>
  new Intl.DateTimeFormat(lang === "de" ? "de-DE" : "en-GB", { weekday: "short" }).format(d);

export const fmtTime = (d: Date, lang: Lang = "de") =>
  new Intl.DateTimeFormat(lang === "de" ? "de-DE" : "en-GB", { hour: "2-digit", minute: "2-digit" }).format(d);
